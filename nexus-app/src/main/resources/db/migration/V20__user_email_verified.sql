-- ============================================================
-- V20 用户邮箱验证状态（Phase 2：已登录用户验证当前绑定邮箱）
--
-- 背景：sys_user.email 可空且允许用户在资料里自行修改，但此前没有任何
-- 「邮箱归属已验证」标记。修改后的邮箱不能当作可信的密码重置目标。
--
-- 【语义】
--   email_verified = 1：当前 email 列上的地址已通过 VERIFY_EMAIL 验证码校验；
--   email_verified = 0：未验证（含无邮箱、刚绑定、刚更换、存量历史邮箱）。
--
-- 【存量兼容】
--   默认值 0：已有邮箱的账号一律视为未验证，不能直接当作可信邮箱；
--   无邮箱用户不受影响；不改 status / 密码 / token_version，不强制立刻验证。
--
-- 只增不改：一条 ADD COLUMN。禁止改写 V1–V19。
-- ============================================================

ALTER TABLE sys_user
    ADD COLUMN email_verified TINYINT NOT NULL DEFAULT 0
        COMMENT '当前邮箱是否已通过归属验证：1 已验证，0 未验证（含空邮箱）';
