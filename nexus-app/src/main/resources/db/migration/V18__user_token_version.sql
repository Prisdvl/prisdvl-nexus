-- ============================================================
-- V18 令牌版本（产品化 Phase 5.6 · P1-15，见 docs/productization-gap-analysis.md）
--
-- 背景：改密码之后，此前签发的 access token 依然有效到 exp（默认 30 分钟）。
-- 全仓原本没有任何提前失效机制——没有 refresh token、没有黑名单、没有版本号；
-- jti 声明虽在 TokenService 里预置（注释写着"为 Phase 11 的登出/吊销预留"），
-- 但从未被存储、也从未被校验。唯一能让令牌全量失效的手段是轮换 nexus.jwt.secret，
-- 那会把**所有人**的令牌一起作废，无法针对单个用户。
--
-- 【为什么是"版本号"而不是 jti 黑名单】
-- 黑名单要存每一支被吊销的令牌（用户越多、签发越频繁，集合越大），
-- 且每次校验都要做成员判断。而用户级版本号只需要一个整数：
-- 令牌带上签发时的版本（claim `ver`），校验时与当前版本比对，不等即失效。
-- 改密码 = 版本 +1 = 该用户此前签发的**全部**令牌同时失效，语义正是我们要的
-- （"改密码 = 全部设备下线"），且存储是 O(用户数) 而不是 O(令牌数)。
--
-- 【代价，如实记在这里】
-- 校验必须能读到"当前版本"，而 ADR-018 第 4 条明确"无状态鉴权不在每个请求上查库"。
-- 因此读路径是 Redis cache-aside（miss 或故障时回落查库）：
--   正常情况下每请求一次 Redis GET；Redis 不可用时退化为每请求一次 SELECT。
-- 这是为"改密码立即失效"付的明确代价，不是疏漏。见 docs/decisions.md ADR-020。
--
-- 【兼容性：存量令牌不会集体下线】
-- 列默认值 0，且没有 ver claim 的令牌按 0 处理。因此本期之前签发的令牌
-- 校验时 0 == 0 通过，直到该用户改密码把版本推到 1。不需要强制所有人重新登录。
--
-- 【为什么不写 db/h2/schema.sql】
-- 该文件已注明是历史遗留（表实际由 Flyway 建），新列只写在这里。
--
-- 只增不改：一条 ADD COLUMN，带默认值，既有行自动为 0。
-- ============================================================

ALTER TABLE sys_user
    ADD COLUMN token_version BIGINT NOT NULL DEFAULT 0
        COMMENT '令牌版本：改密码时 +1，使该用户此前签发的全部 token 立即失效';
