-- ============================================================
-- V6 记录原始文件的存储路径
--
-- 为什么必须落库而不是"按命名规则算出来"：
--   ① 删除文档/知识库时要能删掉磁盘上的原始文件，否则会不断泄漏；
--   ② 增量同步与 Phase 3 的重新嵌入需要重新读取原始文件；
--   ③ 命名规则一旦调整（清洗字符、截断长度），"算出来"的路径就会失配，
--      而落库的路径是事实记录。
-- 长度 512：与 kb_document.source_path 保持一致，且不参与唯一键，无索引长度问题。
-- ============================================================

ALTER TABLE kb_document
    ADD COLUMN stored_path VARCHAR(512) DEFAULT NULL COMMENT '原始文件存储相对路径（用于重新解析与删除时清理）';
