-- ============================================================
-- 目标：技能列表不再为了"这一份多大"把正文整行读出来
-- 只增不改：给 user_skill 加一列 size_bytes，正文与大小分开取
-- 为什么：
--   1. 200 KB × N 份正文只为算一个数字就读进内存，随技能数量线性变差；
--   2. 大小是写入时就知道的事实（UTF-8 字节数），没必要每次重算。
-- 老数据 size_bytes=0 表示"还没算过"：首次按 code 取正文时会回填，
-- 列表里先显示 0——宁可显示 0 也不为了补一个数字去读整篇正文。
-- ============================================================

ALTER TABLE user_skill
    ADD COLUMN size_bytes INT NOT NULL DEFAULT 0 COMMENT '正文 UTF-8 字节数（写入时算好；0 = 老数据，首次打开时回填）';
