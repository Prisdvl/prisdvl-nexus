// 插件市场 / Agent 社区前端验证（mock 登录，无后端依赖）
import { chromium } from 'playwright-core'

const BASE = 'http://localhost:5175'
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const issues = []
const check = (name, ok, extra = '') => {
  console.log(`${ok ? 'ok  ' : 'FAIL'} ${name}${extra ? ' — ' + extra : ''}`)
  if (!ok) issues.push(name)
}

const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.addInitScript(() => {
  localStorage.setItem('nx-proto-tour-done', '1')
  localStorage.setItem('nx-proto-tool-policy', JSON.stringify(['js.sandbox']))
})
page.on('pageerror', (e) => issues.push(`pageerror: ${String(e.message).slice(0, 160)}`))
page.on('console', (m) => { if (m.type() === 'error') issues.push(`console.error: ${m.text().slice(0, 160)}`) })

await page.goto(`${BASE}/#/login`, { waitUntil: 'networkidle' })
await page.waitForSelector('.auth-card')
await page.locator('#li-u').fill('qa-runner')
await page.locator('#li-p').fill('qa-runner-password')
await page.locator('.auth-card .btn-primary', { hasText: '登录' }).click()
await page.waitForSelector('.shell', { timeout: 10000 })
await page.waitForTimeout(900)

check('侧栏导航为 8 项', (await page.locator('.sb-nav button.rubber-segment__item').count()) === 8)
check('导航使用滑动拇指', (await page.locator('.sb-nav .rubber-segment__thumb').count()) === 1)
check('侧栏底部不再有语言按钮', (await page.locator('.sb-row--lang').count()) === 0)

await page.locator('.sb-row--settings').click()
await page.waitForSelector('.settings-dialog')
await page.locator('.settings-dialog__item', { hasText: /账号偏好|Preferences/ }).click()
await page.waitForSelector('.prefs-lang-opt')
check('设置弹窗包含语言分段', (await page.locator('.prefs-lang-opt').count()) === 2)
await page.getByRole('button', { name: 'English' }).click()
await page.waitForTimeout(300)
check('设置切换语言生效', await page.evaluate(() => document.documentElement.lang === 'en'))
await page.keyboard.press('Escape')
await page.waitForTimeout(300)

await page.goto(`${BASE}/#/app/plugins`, { waitUntil: 'networkidle' })
await page.waitForTimeout(1200)
check('插件页标题渲染', (await page.locator('.page-title').first().innerText()).includes('Marketplace') || (await page.locator('.page-title').first().innerText()).includes('插件市场'))
check('桌面端插件页无横向溢出', await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1))
check('插件页不使用卡片网格', (await page.locator('.market-panel .market-card').count()) === 0)
check('插件页按分组展示列表', (await page.locator('.plugin-group__title').count()) >= 2)
check('插件市场使用密集行', (await page.locator('.plugin-row').count()) >= 4)
const pluginCols = await page.locator('.market-panel .plugin-list').first().evaluate((el) => getComputedStyle(el).gridTemplateColumns.split(' ').length)
check('桌面插件列表双列', pluginCols === 2, `${pluginCols} 列`)
await page.locator('.market-tab', { hasText: /Marketplace|插件市场/ }).click()
await page.waitForTimeout(600)
check('插件市场分组列表', (await page.locator('.market-panel .plugin-row').count()) >= 4)
await page.locator('.plugin-row', { hasText: 'Nexus MCP Bridge' }).getByRole('button', { name: /Details|详情/ }).click()
await page.waitForSelector('.plugin-detail')
check('插件详情弹窗', (await page.locator('.plugin-detail').count()) === 1)
await page.keyboard.press('Escape')
await page.waitForTimeout(200)
await page.locator('.market-tab', { hasText: 'MCP' }).click()
await page.waitForTimeout(500)
check('MCP 服务行', (await page.locator('.mcp-row').count()) >= 3)
await page.getByRole('button', { name: 'Import skill' }).click()
await page.waitForSelector('.import-block')
await page.locator('.import-block__text').fill('---\nname: demo-skill\nversion: 1.0.0\ndescription: Demo skill\n---')
await page.locator('.dialog .dfoot .btn-primary').click()
await page.waitForTimeout(300)
await page.locator('.market-tab', { hasText: /Installed|已安装/ }).click()
await page.waitForTimeout(400)
check('技能导入成功', (await page.locator('.skill-row').count()) >= 1)

await page.goto(`${BASE}/#/app/community`, { waitUntil: 'networkidle' })
await page.waitForTimeout(1200)
check('社区标题渲染', (await page.locator('.page-title').first().innerText()).includes('Community') || (await page.locator('.page-title').first().innerText()).includes('社区'))
check('桌面端社区页无横向溢出', await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1))
check('社区精选卡', (await page.locator('.community-hero').count()) === 1)
check('社区卡片', (await page.locator('.community-grid .market-card').count()) >= 4)
check('社区卡片不再使用圆角标签', (await page.locator('.community-grid .market-card .chip').count()) === 0)
check('社区元信息使用图标文字行', (await page.locator('.community-grid .market-card .meta-inline').count()) >= 4)
await page.locator('.market-tab', { hasText: /我的发布|My publishing/ }).click()
await page.waitForTimeout(600)
const heroCollapsed = await page.locator('.community-hero-wrap').evaluate((el) => Math.round(el.getBoundingClientRect().height))
check('切到我的发布时精选区平滑收起', heroCollapsed < 4, `${heroCollapsed}px`)
await page.locator('.market-tab', { hasText: /发现|Discover/ }).click()
await page.waitForTimeout(500)
check('切回发现时精选区恢复', (await page.locator('.community-hero').count()) === 1)
check('页签有滑动背景', (await page.locator('.market-tab__bg').count()) === 1)
await page.locator('.community-grid .market-card').first().getByRole('button', { name: 'Details' }).click()
await page.waitForSelector('.agent-detail')
check('社区详情弹窗', (await page.locator('.agent-detail').count()) === 1)
await page.keyboard.press('Escape')
await page.waitForTimeout(200)
await page.getByRole('button', { name: 'Publish agent' }).click()
await page.waitForSelector('.dialog .outer-container')
check('发布向导打开', (await page.locator('.dialog .step-indicator-row').count()) === 1)
await page.locator('#cm-name').fill('QA 发布的 Agent')
await page.getByRole('button', { name: 'Continue' }).first().click()
await page.waitForTimeout(400)
await page.getByRole('button', { name: 'Continue' }).first().click()
await page.waitForTimeout(400)
await page.locator('.dialog .footer-nav .next-button').click()
await page.waitForTimeout(300)
await page.locator('.market-tab', { hasText: 'My publishing' }).click()
await page.waitForTimeout(500)
check('我的发布出现新条目', (await page.locator('.mine-row').count()) >= 1)

await page.setViewportSize({ width: 390, height: 844 })
await page.goto(`${BASE}/#/app/plugins`, { waitUntil: 'networkidle' })
await page.waitForTimeout(1000)
check('手机端插件页无横向溢出', await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1))
const pluginColsMobile = await page.locator('.market-panel .plugin-list').first().evaluate((el) => getComputedStyle(el).gridTemplateColumns.split(' ').length)
check('手机端插件列表单列', pluginColsMobile === 1, `${pluginColsMobile} 列`)
await page.goto(`${BASE}/#/app/community`, { waitUntil: 'networkidle' })
await page.waitForTimeout(1000)
check('手机端社区页无横向溢出', await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1))

console.log(issues.length === 0 ? 'ALL OK' : `ISSUES: ${issues.join(' | ')}`)
await browser.close()
process.exit(issues.length ? 1 : 0)
