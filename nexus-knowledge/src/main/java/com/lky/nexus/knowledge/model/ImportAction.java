package com.lky.nexus.knowledge.model;

/**
 * 导入动作（增量同步时对每个文件的判定结果）。
 *
 * <p>比"跳过 / 更新"更细的分法，是为了<b>避免不必要的重新嵌入</b>——
 * 嵌入按 Token 计费且慢，而大多数导入其实只有少量文件真的变了。
 */
public enum ImportAction {
    /** 新文件。 */
    CREATED,
    /** 正文变化，需重建切片与向量。 */
    UPDATED,
    /**
     * 只有元数据变化（frontmatter/标签/标题），正文未变。
     *
     * <p>典型场景：给笔记加了个 tag。此时字节变了（`file_hash` 变），
     * 但解析后的正文一模一样（`content_hash` 相同），因此<b>切片可以原样保留</b>，
     * 不必删除重建——保住了向量，也就不必重新嵌入。
     */
    METADATA_ONLY,
    /**
     * 文件被改名/移动（路径变了、内容没变）。
     *
     * <p>通过 `file_hash` 把"新路径"与"刚消失的旧文档"配对识别出来。
     * 直接当成"删除 + 新增"也能得到正确结果，但会让整篇文档重新嵌入；
     * 识别为改名后只需改路径字段，切片与向量原样保留。
     */
    RENAMED,
    /** 未变化，跳过（增量同步省时省钱的关键）。 */
    SKIPPED,
    /** 库里存在但本次导入清单里没有 → 删除。 */
    DELETED,
    /** 处理失败（message 里是原因）。 */
    FAILED
}
